-- The whole schema, for PostgreSQL.
--
-- This is the state the eleven SQLite migrations arrived at, written once for
-- Postgres. Two conventions carry over unchanged so no query has to know which
-- database it is talking to:
--   * dates and timestamps are ISO-8601 TEXT (YYYY-MM-DD, YYYY-MM-01 for an
--     accounting month, full ISO for a timestamp), compared as strings;
--   * flags are 0/1 INTEGERs.
-- Money is BIGINT cents; percentages are INTEGER basis points.

CREATE TABLE users (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email          TEXT NOT NULL,
  name           TEXT NOT NULL,
  password_hash  TEXT NOT NULL,
  -- 'partner' is retired; see auth/permissions.js. Kept so no row is orphaned.
  role           TEXT NOT NULL CHECK (role IN ('owner','partner','editor','viewer')),
  is_active      INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
  must_change_pw INTEGER NOT NULL DEFAULT 0 CHECK (must_change_pw IN (0,1)),
  failed_logins  INTEGER NOT NULL DEFAULT 0,
  locked_until   TEXT,
  last_login_at  TEXT,
  created_by     BIGINT REFERENCES users(id),
  created_at     TEXT NOT NULL,
  updated_by     BIGINT REFERENCES users(id),
  updated_at     TEXT NOT NULL
);
CREATE UNIQUE INDEX idx_users_email ON users(lower(email));

CREATE TABLE sessions (
  id          TEXT PRIMARY KEY,
  user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash  TEXT NOT NULL,
  csrf_token  TEXT NOT NULL,
  ip          TEXT,
  user_agent  TEXT,
  created_at  TEXT NOT NULL,
  expires_at  TEXT NOT NULL,
  revoked_at  TEXT
);
CREATE INDEX idx_sessions_expires ON sessions(expires_at);
CREATE INDEX idx_sessions_user ON sessions(user_id);

CREATE TABLE user_permissions (
  user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  permission TEXT NOT NULL,
  effect     TEXT NOT NULL CHECK (effect IN ('allow','deny')),
  granted_by BIGINT REFERENCES users(id),
  created_at TEXT NOT NULL,
  PRIMARY KEY (user_id, permission)
);

CREATE TABLE user_scopes (
  user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  scope_type TEXT NOT NULL CHECK (scope_type IN ('org_unit')),
  scope_id   BIGINT NOT NULL,
  created_by BIGINT REFERENCES users(id),
  created_at TEXT NOT NULL,
  PRIMARY KEY (user_id, scope_type, scope_id)
);

CREATE TABLE settings (
  key         TEXT PRIMARY KEY,
  value       TEXT NOT NULL,
  updated_by  BIGINT,
  updated_at  TEXT NOT NULL
);

CREATE TABLE audit_log (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type  TEXT NOT NULL,
  entity_id    TEXT,
  action       TEXT NOT NULL,
  user_id      BIGINT REFERENCES users(id),
  user_label   TEXT,
  reason       TEXT,
  changes_json TEXT,
  ip           TEXT,
  created_at   TEXT NOT NULL
);
CREATE INDEX idx_audit_entity ON audit_log(entity_type, entity_id);
CREATE INDEX idx_audit_time   ON audit_log(created_at);
CREATE INDEX idx_audit_user   ON audit_log(user_id);

CREATE TABLE attachments (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  filename     TEXT NOT NULL,
  stored_name  TEXT NOT NULL UNIQUE,
  mime_type    TEXT NOT NULL,
  byte_size    BIGINT NOT NULL,
  checksum     TEXT,
  uploaded_by  BIGINT REFERENCES users(id),
  created_at   TEXT NOT NULL
);

CREATE TABLE org_units (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         TEXT NOT NULL,
  kind         TEXT NOT NULL CHECK (kind IN ('main','sub','ssn')),
  parent_id    BIGINT REFERENCES org_units(id),
  -- What an SSN KEEPS of what remains. 3000 = 30%. The remainder travels up.
  share_bps    INTEGER CHECK (share_bps IS NULL OR (share_bps >= 0 AND share_bps <= 10000)),
  code         TEXT,
  description  TEXT,
  is_active    INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
  created_by   BIGINT REFERENCES users(id),
  created_at   TEXT NOT NULL,
  updated_by   BIGINT REFERENCES users(id),
  updated_at   TEXT NOT NULL,

  -- A main company has no parent; anything else must have one.
  CHECK ((kind = 'main' AND parent_id IS NULL) OR (kind <> 'main' AND parent_id IS NOT NULL)),
  -- Only an SSN carries a share.
  CHECK (kind = 'ssn' OR share_bps IS NULL),
  CHECK (kind <> 'ssn' OR share_bps IS NOT NULL)
);
CREATE INDEX idx_org_units_kind ON org_units(kind, is_active);
CREATE UNIQUE INDEX idx_org_units_name ON org_units(parent_id, lower(name));
CREATE INDEX idx_org_units_parent ON org_units(parent_id, kind);

CREATE TABLE expense_categories (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT NOT NULL,
  is_active  INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
  is_system  INTEGER NOT NULL DEFAULT 0 CHECK (is_system IN (0,1)),
  created_by BIGINT REFERENCES users(id),
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE UNIQUE INDEX idx_expense_categories_name ON expense_categories(lower(name));

CREATE TABLE jobs (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference        TEXT NOT NULL UNIQUE,
  ssn_id           BIGINT NOT NULL REFERENCES org_units(id),
  title            TEXT NOT NULL,
  client_name      TEXT,
  -- 'w2' withholds tax before crediting; '1099' normally credits in full.
  tax_category     TEXT NOT NULL DEFAULT '1099' CHECK (tax_category IN ('w2','1099')),
  -- Held from each salary's CREDITED amount, not from the invoice. 1000 = 10%.
  tax_hold_bps     INTEGER NOT NULL DEFAULT 0
                     CHECK (tax_hold_bps >= 0 AND tax_hold_bps <= 10000),
  joining_date     TEXT NOT NULL,
  is_active        INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
  notes            TEXT,
  attachment_id    BIGINT REFERENCES attachments(id),
  is_demo          INTEGER NOT NULL DEFAULT 0 CHECK (is_demo IN (0,1)),
  created_by       BIGINT REFERENCES users(id),
  created_at       TEXT NOT NULL,
  updated_by       BIGINT REFERENCES users(id),
  updated_at       TEXT NOT NULL
);
CREATE INDEX idx_jobs_joining ON jobs(joining_date);
CREATE INDEX idx_jobs_ssn ON jobs(ssn_id, is_active);

CREATE TABLE salaries (
  id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference              TEXT NOT NULL UNIQUE,
  job_id                 BIGINT NOT NULL REFERENCES jobs(id),
  accounting_month       TEXT NOT NULL,
  -- What was billed.
  invoice_amount_cents   BIGINT NOT NULL CHECK (invoice_amount_cents >= 0),
  -- What actually arrived. The difference is what the hiring company withheld.
  credited_amount_cents  BIGINT NOT NULL CHECK (credited_amount_cents >= 0),
  credit_date            TEXT,
  status                 TEXT NOT NULL DEFAULT 'active'
                           CHECK (status IN ('draft','active','void')),
  notes                  TEXT,
  attachment_id          BIGINT REFERENCES attachments(id),
  is_demo                INTEGER NOT NULL DEFAULT 0 CHECK (is_demo IN (0,1)),
  created_by             BIGINT REFERENCES users(id),
  created_at             TEXT NOT NULL,
  updated_by             BIGINT REFERENCES users(id),
  updated_at             TEXT NOT NULL,
  -- Descriptive only: the accounting month decides where the money lands.
  pay_period_from        TEXT,
  pay_period_to          TEXT,

  -- More cannot arrive than was billed, or the withheld amount goes negative.
  CHECK (credited_amount_cents <= invoice_amount_cents),
  -- A pay period must not end before it starts (either end may be open).
  CONSTRAINT salaries_period_order CHECK (
    pay_period_from IS NULL OR pay_period_to IS NULL OR pay_period_to >= pay_period_from
  )
);
CREATE INDEX idx_salaries_credit_date ON salaries(credit_date);
CREATE INDEX idx_salaries_job_month ON salaries(job_id, accounting_month, status);
CREATE INDEX idx_salaries_month ON salaries(accounting_month, status);
CREATE INDEX idx_salaries_period ON salaries(pay_period_from, pay_period_to);

CREATE TABLE expenses (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference         TEXT NOT NULL UNIQUE,
  ssn_id            BIGINT NOT NULL REFERENCES org_units(id),
  accounting_month  TEXT NOT NULL,
  expense_date      TEXT NOT NULL,
  amount_cents      BIGINT NOT NULL CHECK (amount_cents >= 0),
  category_id       BIGINT NOT NULL REFERENCES expense_categories(id),
  description       TEXT,
  vendor            TEXT,
  payment_method    TEXT,
  payment_reference TEXT,
  status            TEXT NOT NULL DEFAULT 'approved' CHECK (status IN ('draft','approved','void')),
  attachment_id     BIGINT REFERENCES attachments(id),
  is_demo           INTEGER NOT NULL DEFAULT 0 CHECK (is_demo IN (0,1)),
  created_by        BIGINT REFERENCES users(id),
  created_at        TEXT NOT NULL,
  updated_by        BIGINT REFERENCES users(id),
  updated_at        TEXT NOT NULL
);
CREATE INDEX idx_expenses_category ON expenses(category_id);
CREATE INDEX idx_expenses_date ON expenses(expense_date, status);
CREATE INDEX idx_expenses_month ON expenses(accounting_month, status);
CREATE INDEX idx_expenses_ssn_month ON expenses(ssn_id, accounting_month, status);

CREATE TABLE tax_overrides (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ssn_id           BIGINT NOT NULL REFERENCES org_units(id) ON DELETE CASCADE,
  accounting_month TEXT NOT NULL,
  amount_cents     BIGINT NOT NULL CHECK (amount_cents >= 0),
  reason           TEXT NOT NULL,
  created_by       BIGINT REFERENCES users(id),
  created_at       TEXT NOT NULL,
  updated_by       BIGINT REFERENCES users(id),
  updated_at       TEXT NOT NULL
);
CREATE UNIQUE INDEX idx_tax_override_ssn_month ON tax_overrides(ssn_id, accounting_month);
