import ExcelJS from 'exceljs';
import { fromCents } from './money.js';

/**
 * Export helpers.
 *
 * Columns are described once and rendered to both CSV and Excel, so the two
 * formats can never drift apart. Money is emitted as a plain 2dp decimal, not a
 * locale-formatted string, so spreadsheets parse it as a number.
 */

const escapeCsv = (value) => {
  if (value === null || value === undefined) return '';
  const s = String(value);
  return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

/** Neutralises spreadsheet formula injection in text cells. */
const deFormula = (value) => {
  if (typeof value !== 'string') return value;
  return /^[=+\-@\t\r]/.test(value) ? `'${value}` : value;};

function cellValue(row, column) {
  const raw = typeof column.value === 'function' ? column.value(row) : row[column.key];
  if (column.type === 'money') return raw === null || raw === undefined ? '' : Number(fromCents(raw));
  if (column.type === 'percent') return raw === null || raw === undefined ? '' : Number(raw) / 10000;
  if (column.type === 'number') return raw === null || raw === undefined ? '' : Number(raw);
  return raw === null || raw === undefined ? '' : String(raw);
}

/**
 * The reporting basis banner. Every export states which dates it was built on,
 * so an accounting-month report can never be mistaken for a cash-receipt one.
 */
export function basisLines(meta = {}) {
  const lines = [];
  if (meta.title) lines.push([meta.title]);
  if (meta.basis) lines.push([`Reporting basis: ${meta.basis}`]);
  for (const [label, value] of Object.entries(meta.filters ?? {})) {
    if (value !== null && value !== undefined && value !== '') lines.push([`${label}: ${value}`]);
  }
  lines.push([`Generated: ${new Date().toISOString()}`]);
  if (meta.generatedBy) lines.push([`Generated by: ${meta.generatedBy}`]);
  if (meta.note) lines.push([meta.note]);
  lines.push([]);
  return lines;
}

export function toCsv({ columns, rows, meta }) {
  const out = [];
  for (const line of basisLines(meta)) out.push(line.map(escapeCsv).join(','));
  out.push(columns.map((c) => escapeCsv(c.header)).join(','));
  for (const row of rows) {
    out.push(columns.map((c) => escapeCsv(deFormula(cellValue(row, c)))).join(','));
  }
  if (meta?.totals) {
    out.push([]);
    for (const [label, value] of Object.entries(meta.totals)) {
      out.push([escapeCsv(label), escapeCsv(typeof value === 'number' ? fromCents(value) : value)].join(','));
    }
  }
  return `﻿${out.join('\r\n')}\r\n`;
}

export async function toXlsx({ columns, rows, meta, sheetName = 'Report' }) {
  const wb = new ExcelJS.Workbook();
  wb.creator = meta?.generatedBy ?? 'Vault';
  wb.created = new Date();
  const ws = wb.addWorksheet(String(sheetName).slice(0, 31).replace(/[\\/*?:[\]]/g, '-'));

  const banner = basisLines(meta);
  for (const line of banner) {
    const row = ws.addRow(line);
    row.font = { bold: line === banner[0], color: { argb: 'FF444444' }, size: line === banner[0] ? 13 : 10 };
  }

  const header = ws.addRow(columns.map((c) => c.header));
  header.font = { bold: true, color: { argb: 'FFFFFFFF' } };
  header.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF111827' } };
  header.alignment = { vertical: 'middle' };

  for (const row of rows) {
    const values = columns.map((c) => {
      const v = cellValue(row, c);
      return typeof v === 'string' ? deFormula(v) : v;
    });
    ws.addRow(values);
  }

  columns.forEach((column, i) => {
    const col = ws.getColumn(i + 1);
    col.width = Math.min(44, Math.max(12, String(column.header).length + 4, column.width ?? 0));
    if (column.type === 'money') col.numFmt = '#,##0.00';
    if (column.type === 'percent') col.numFmt = '0.00%';
    if (column.type === 'number') col.numFmt = '#,##0';
  });

  if (meta?.totals) {
    ws.addRow([]);
    for (const [label, value] of Object.entries(meta.totals)) {
      const row = ws.addRow([label, typeof value === 'number' ? Number(fromCents(value)) : value]);
      row.font = { bold: true };
      if (typeof value === 'number') row.getCell(2).numFmt = '#,##0.00';
    }
  }

  ws.views = [{ state: 'frozen', ySplit: banner.length + 1 }];
  const buffer = await wb.xlsx.writeBuffer();
  return Buffer.from(buffer);
}

/** Minimal HTML statement, styled for printing to PDF from the browser. */
export function toPrintableHtml({ title, basis, filters = {}, sections = [] }) {
  const esc = (s) => String(s ?? '').replace(/[&<>"']/g, (c) =>    ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

  const filterRows = Object.entries(filters)
    .filter(([, v]) => v !== null && v !== undefined && v !== '')
    .map(([k, v]) => `<div><span>${esc(k)}</span><strong>${esc(v)}</strong></div>`).join('');

  const body = sections.map((section) => `
    <section>
      <h2>${esc(section.heading)}</h2>
      ${section.summary ? `<div class="summary">${section.summary.map((s) =>
        `<div class="card"><span>${esc(s.label)}</span><strong>${esc(s.value)}</strong></div>`).join('')}</div>` : ''}
      ${section.columns ? `<table>
        <thead><tr>${section.columns.map((c) =>
          `<th class="${c.align === 'right' ? 'r' : ''}">${esc(c.header)}</th>`).join('')}</tr></thead>
        <tbody>${section.rows.map((row) => `<tr>${section.columns.map((c) =>
          `<td class="${c.align === 'right' ? 'r' : ''}">${esc(
            typeof c.value === 'function' ? c.value(row) : row[c.key])}</td>`).join('')}</tr>`).join('')}
        </tbody></table>` : ''}
    </section>`).join('');

  return `<!doctype html><html><head><meta charset="utf-8"><title>${esc(title)}</title>
<style>
  :root { color-scheme: light; }
  * { box-sizing: border-box; }
  body { font: 13px/1.5 -apple-system, "Segoe UI", Roboto, system-ui, sans-serif;
         color: #111827; margin: 0; padding: 40px; background: #fff; }
  h1 { font-size: 22px; margin: 0 0 4px; letter-spacing: -0.02em; }
  h2 { font-size: 14px; text-transform: uppercase; letter-spacing: .08em;
       color: #6b7280; margin: 32px 0 10px; }
  .basis { color: #374151; font-size: 12px; margin-bottom: 18px; }
  .meta div { display: flex; gap: 8px; font-size: 12px; color: #4b5563; }
  .meta span { min-width: 150px; color: #9ca3af; }
  table { width: 100%; border-collapse: collapse; font-variant-numeric: tabular-nums; }
  th, td { padding: 7px 10px; border-bottom: 1px solid #e5e7eb; text-align: left; }
  th { font-size: 11px; text-transform: uppercase; letter-spacing: .05em; color: #6b7280; }
  .r { text-align: right; }
  .summary { display: grid; grid-template-columns: repeat(auto-fit, minmax(150px, 1fr));
             gap: 10px; margin-bottom: 14px; }
  .card { border: 1px solid #e5e7eb; border-radius: 8px; padding: 10px 12px; }
  .card span { display: block; font-size: 11px; color: #6b7280; text-transform: uppercase;
               letter-spacing: .05em; }
  .card strong { font-size: 17px; }
  footer { margin-top: 36px; padding-top: 12px; border-top: 1px solid #e5e7eb;
           font-size: 11px; color: #9ca3af; }
  @media print { body { padding: 0; } @page { margin: 16mm; } }
</style></head><body>
<h1>${esc(title)}</h1>
<div class="basis">Reporting basis: <strong>${esc(basis)}</strong></div>
<div class="meta">${filterRows}</div>
${body}
<footer>Generated ${esc(new Date().toISOString())}. Tax hold figures are an internal
 reserve, not a calculated tax liability.</footer>
<script>window.addEventListener('load', () => { if (location.hash === '#print') window.print(); });</script>
</body></html>`;
}
